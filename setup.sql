create table if not exists public.apps (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(trim(name)) between 1 and 160),
  icon text not null default '',
  category text not null default '',
  descr text not null default '',
  ver text not null default '',
  size text not null default '',
  url text not null check (url ~* '^https?://'),
  downloads bigint not null default 0 check (downloads >= 0),
  created_at timestamptz not null default now()
);

-- Keep updated schema compatible with an existing table.
alter table public.apps add column if not exists icon text not null default '';
alter table public.apps add column if not exists category text not null default '';
alter table public.apps add column if not exists descr text not null default '';
alter table public.apps add column if not exists ver text not null default '';
alter table public.apps add column if not exists size text not null default '';
alter table public.apps add column if not exists url text not null default '';
alter table public.apps add column if not exists downloads bigint not null default 0;
alter table public.apps add column if not exists created_at timestamptz not null default now();

alter table public.apps enable row level security;

drop policy if exists "Anyone can view apps" on public.apps;
create policy "Anyone can view apps"
  on public.apps for select
  to anon, authenticated
  using (true);

-- Replace admin@example.com with your actual sign-in email.
drop policy if exists "Admins can insert apps" on public.apps;
create policy "Admins can insert apps"
  on public.apps for insert
  to authenticated
  with check (lower(coalesce(auth.jwt() ->> 'email', '')) = lower('admin@example.com'));

drop policy if exists "Admins can update apps" on public.apps;
create policy "Admins can update apps"
  on public.apps for update
  to authenticated
  using (lower(coalesce(auth.jwt() ->> 'email', '')) = lower('admin@example.com'))
  with check (lower(coalesce(auth.jwt() ->> 'email', '')) = lower('admin@example.com'));

drop policy if exists "Admins can delete apps" on public.apps;
create policy "Admins can delete apps"
  on public.apps for delete
  to authenticated
  using (lower(coalesce(auth.jwt() ->> 'email', '')) = lower('admin@example.com'));

-- Count downloads without allowing visitors to update arbitrary app fields.
create or replace function public.inc_downloads(app_id bigint)
returns void
language sql
security definer
set search_path = ''
as $$
  update public.apps
  set downloads = downloads + 1
  where id = app_id;
$$;

revoke all on function public.inc_downloads(bigint) from public;
grant execute on function public.inc_downloads(bigint) to anon, authenticated;

grant select on public.apps to anon, authenticated;
grant insert, update, delete on public.apps to authenticated;
grant usage, select on sequence public.apps_id_seq to authenticated;

create index if not exists apps_created_at_idx on public.apps (created_at desc);
create index if not exists apps_category_idx on public.apps (category);
